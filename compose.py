"""Композиция сцены: объединение объектов (vox/рельеф) в одну .litematic.

Каждый объект: gridB64 (1 байт = блок, порядок региона x→z→y), палитра
имен блоков, размеры и смещение. Объединение — общая bounding box;
правила перекрытия:
- overwrite=True: объект затирает всё (включая air);
- overwrite=False («вживление»): air объекта пропускается — картинку можно
  поместить внутрь модели, не вырезая её.
"""

import base64

import numpy as np

import config
from litematic.writer import build_litematic_bytes
from palette import AIR_CODE, AIR_NAME, PALETTE, block_name
from vox import _render_preview

_PALETTE_NAMES = {b.name for b in PALETTE}
_CODE_OF = {b.name: i for i, b in enumerate(PALETTE)}


class ComposeError(Exception):
    """Ошибка описания сцены; code — машиночитаемый код для API."""

    def __init__(self, code: str, message: str):
        self.code = code
        self.message = message
        super().__init__(message)


def _decode_object(obj: dict) -> dict:
    try:
        grid_b64 = obj["gridB64"]
        w, h, d = int(obj["width"]), int(obj["height"]), int(obj["depth"])
        ox, oy, oz = (int(v) for v in obj["offset"])
        names = [str(n) for n in obj["palette"]]
        overwrite = bool(obj.get("overwrite", True))
    except (KeyError, TypeError, ValueError):
        raise ComposeError("invalid_params", "Некорректное описание объекта сцены")
    if w < 1 or h < 1 or d < 1:
        raise ComposeError("invalid_params", "Размеры объекта должны быть ≥ 1")
    if not names:
        raise ComposeError("invalid_params", "Пустая палитра объекта")
    for n in names:
        if n != AIR_NAME and n not in _PALETTE_NAMES:
            raise ComposeError("invalid_params", f"Неизвестный блок: {n}")
    try:
        raw = base64.b64decode(grid_b64, validate=True)
    except Exception:
        raise ComposeError("invalid_params", "gridB64 не является base64")
    if len(raw) != w * h * d:
        raise ComposeError(
            "invalid_params", f"gridB64: ожидалось {w * h * d} байт, получено {len(raw)}"
        )
    grid = np.frombuffer(raw, dtype=np.uint8).astype(np.int64).reshape(h, d, w)
    if grid.max() >= len(names):
        raise ComposeError("invalid_params", "Индекс блока вне палитры объекта")
    codes = [
        AIR_CODE if n == AIR_NAME else _CODE_OF[n]
        for n in names
    ]
    return {
        "grid": grid,
        "codes": np.array(codes, dtype=np.int64),
        "offset": (ox, oy, oz),
        "overwrite": overwrite,
        "size": (w, h, d),
    }


def compose_litematic(objects: list[dict], created_ms: int, modified_ms: int) -> bytes:
    """Объединяет объекты сцены в .litematic (gzip-NBT байты)."""
    dec = [_decode_object(o) for o in objects]

    minx = min(o["offset"][0] for o in dec)
    miny = min(o["offset"][1] for o in dec)
    minz = min(o["offset"][2] for o in dec)
    maxx = max(o["offset"][0] + o["size"][0] for o in dec)
    maxy = max(o["offset"][1] + o["size"][1] for o in dec)
    maxz = max(o["offset"][2] + o["size"][2] for o in dec)
    sx, sy, sz = maxx - minx, maxy - miny, maxz - minz
    if sx < 1 or sy < 1 or sz < 1:
        raise ComposeError("invalid_params", "Пустая сцена")
    volume = sx * sy * sz
    if volume > config.MAX_COMPOSE_VOLUME:
        raise ComposeError(
            "volume_too_large",
            f"Объём сцены {sx}×{sy}×{sz} = {volume} блоков превышает лимит "
            f"({config.MAX_COMPOSE_VOLUME})",
        )

    arr = np.full((sy, sz, sx), AIR_CODE, dtype=np.int64)
    for o in dec:
        x0 = o["offset"][0] - minx
        y0 = o["offset"][1] - miny
        z0 = o["offset"][2] - minz
        w, h, d = o["size"]
        g = o["codes"][o["grid"]]  # (h, d, w) кодов блоков
        region = arr[y0 : y0 + h, z0 : z0 + d, x0 : x0 + w]
        if o["overwrite"]:
            region[:] = g
        else:
            mask = g != AIR_CODE  # вживление: air не затирает
            region[mask] = g[mask]

    flat = arr.ravel()
    binc = np.bincount(flat, minlength=len(PALETTE) + 1)
    used = sorted(
        (i for i in range(len(PALETTE) + 1) if binc[i] > 0),
        key=lambda i: (-binc[i], i),
    )
    order = {i: pos for pos, i in enumerate(used)}
    grid = [order[i] for i in flat.tolist()]
    preview = _render_preview(arr.transpose(2, 0, 1))  # (y,z,x) → (x,y,z)
    return build_litematic_bytes(
        name="scene",
        description=f"composed scene {sx}×{sy}×{sz} — generated by img2litematic",
        author=config.AUTHOR,
        size=(sx, sy, sz),
        palette_names=[block_name(i) for i in used],
        block_indices=grid,
        created_ms=created_ms,
        modified_ms=modified_ms,
        preview_png=preview,
        region_name=config.REGION_NAME,
        data_version=config.MINECRAFT_DATA_VERSION,
    )
